    @staticmethod
    def clean_drive_folder_name(raw_name: str) -> str:
        """Làm sạch tên thư mục Google Drive để so khớp/tạo NotebookLM có tên trùng khớp"""
        if not raw_name:
            return "Tax-Công tác văn thư"
        s = str(raw_name).replace("📁", "").replace("⭐", "").replace("[Mặc định]", "").strip()
        return s or "Tax-Công tác văn thư"

    @staticmethod
    def ensure_notebook_for_folder(folder_name: str, folder_id: str = "") -> Dict[str, Any]:
        """
        Tìm hoặc tự động khởi tạo một Notebook trong hệ thống có tên trùng với tên thư mục Google Drive được chọn.
        """
        clean_name = ConfigManager.clean_drive_folder_name(folder_name)
        config = ConfigManager.load_config()
        notebooks = config.get("notebooks")
        if not notebooks or not isinstance(notebooks, list):
            notebooks = [nb.copy() for nb in DEFAULT_NOTEBOOKS]

        target_lower = clean_name.lower().strip()
        matched_nb = None
        for nb in notebooks:
            nb_name = str(nb.get("name", "")).strip()
            nb_folder = str(nb.get("folder_name", "")).strip()
            if nb_name.lower() == target_lower or nb_folder.lower() == target_lower:
                matched_nb = nb
                break

        if not matched_nb:
            # Tự động tạo mới Notebook có tên trùng với thư mục Google Drive
            slug = re.sub(r'[^a-zA-Z0-9]+', '_', clean_name.lower()).strip('_')[:24] or uuid.uuid4().hex[:6]
            matched_nb = {
                "id": f"nb_drive_{slug}",
                "name": clean_name,
                "url": "https://notebooklm.google.com/",
                "folder_name": clean_name,
                "drive_folder_id": folder_id,
                "description": f"Kho tri thức quy định đồng bộ từ thư mục Google Drive '{clean_name}'",
                "is_default": False
            }
            notebooks.insert(0, matched_nb)
            config["notebooks"] = notebooks
            ConfigManager.save_config(config)

        return matched_nb

