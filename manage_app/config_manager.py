class ConfigManager:
    @staticmethod
    def load_config() -> Dict[str, Any]:
        """Tải cấu hình từ config.json, khởi tạo mặc định nếu chưa có"""
        if not os.path.exists(CONFIG_FILE):
            ConfigManager.save_config(DEFAULT_CONFIG)
            return DEFAULT_CONFIG.copy()

        try:
            with open(CONFIG_FILE, "r", encoding="utf-8") as f:
                data = json.load(f)
                merged = DEFAULT_CONFIG.copy()
                for key, val in data.items():
                    if isinstance(val, dict) and key in merged and isinstance(merged[key], dict):
                        merged[key].update(val)
                    else:
                        merged[key] = val
                
                # Đảm bảo danh mục sources có dữ liệu chuẩn
                if "scanner" not in merged or not merged["scanner"].get("sources"):
                    if "scanner" not in merged:
                        merged["scanner"] = {}
                    merged["scanner"]["sources"] = DEFAULT_SOURCES

                return merged
        except Exception as e:
            print(f"[ConfigManager] Lỗi đọc config: {e}")
            return DEFAULT_CONFIG.copy()

    @staticmethod
    def save_config(config_data: Dict[str, Any]) -> bool:
        """Lưu toàn bộ hoặc cập nhật config.json"""
        try:
            with open(CONFIG_FILE, "w", encoding="utf-8") as f:
                json.dump(config_data, f, ensure_ascii=False, indent=2)
            return True
        except Exception as e:
            print(f"[ConfigManager] Lỗi lưu config: {e}")
            return False

    @staticmethod
    def update_last_fields(fields: str) -> bool:
        """Lưu lại giá trị lĩnh vực nhập sau cùng để duy trì trạng thái"""
        config = ConfigManager.load_config()
        config["last_fields"] = fields.strip()
        return ConfigManager.save_config(config)

    @staticmethod
    def get_last_fields() -> str:
        """Lấy giá trị lĩnh vực nhập sau cùng"""
        config = ConfigManager.load_config()
        return config.get("last_fields", DEFAULT_TAX_FIELDS)

    @staticmethod
    def update_drive_config(drive_data: Dict[str, Any]) -> bool:
        """Cập nhật thiết lập Google Drive"""
        config = ConfigManager.load_config()
        if "google_drive" not in config:
            config["google_drive"] = {}
        config["google_drive"].update(drive_data)
        return ConfigManager.save_config(config)

    @staticmethod
    def get_sources() -> List[Dict[str, Any]]:
        """Lấy danh mục các website nguồn dò quét, tự động chuẩn hóa domain chuẩn chính phủ"""
        config = ConfigManager.load_config()
        sources = config.get("scanner", {}).get("sources", DEFAULT_SOURCES)
        
        # Tự động cập nhật nếu có nguồn cũ congbao.gov.vn sang congbao.chinhphu.vn
        has_changed = False
        for s in sources:
            if s.get("domain", "").lower() in ["congbao.gov.vn", "www.congbao.gov.vn"]:
                s["domain"] = "congbao.chinhphu.vn"
                has_changed = True

        if has_changed:
            ConfigManager.save_sources(sources)

        return sources

    @staticmethod
    def save_sources(sources: List[Dict[str, Any]]) -> bool:
        """Lưu danh mục các website nguồn"""
        config = ConfigManager.load_config()
        if "scanner" not in config:
            config["scanner"] = {}
        config["scanner"]["sources"] = sources
        return ConfigManager.save_config(config)

    @staticmethod
    def add_source(domain: str, name: str) -> Dict[str, Any]:
        """Thêm mới website nguồn"""
        sources = ConfigManager.get_sources()
        clean_domain = domain.strip().lower().replace("https://", "").replace("http://", "").strip("/")
        
        # Kiểm tra trùng lặp
        for s in sources:
            if s.get("domain", "").lower() == clean_domain:
                return {"success": False, "message": "Website này đã tồn tại trong danh mục."}

        new_item = {
            "id": str(uuid.uuid4())[:8],
            "domain": clean_domain,
            "name": name.strip() or clean_domain,
            "enabled": True
        }
        sources.append(new_item)
        ConfigManager.save_sources(sources)
