    @staticmethod
    def extract_youtube_id(url_or_id: str) -> str:
        if not url_or_id:
            return ""
        s = str(url_or_id).strip()
        match = re.search(r'(?:youtu\.be/|youtube\.com/(?:embed/|v/|watch\?v=|watch\?.+&v=))([\w-]{11})', s)
        if match:
            return match.group(1)
        if re.match(r'^[\w-]{11}$', s):
            return s
        return s

